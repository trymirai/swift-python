"""Collect module declarations, resolve annotations and assemble interface files."""

import ast

from ..exports.functions import module_parts
from . import exports, source
from .annotations import BUILTINS, Annotations
from .formatting import documentation

_HEADER = "# Generated by swift-python. Changes will be overwritten."


class Module:
    def __init__(self, record, bindings: dict, fields: dict) -> None:
        self.name, self.documentation, text, functions, classes = record
        module_parts(self.name)
        self.bindings, self.fields = bindings, fields
        self.functions = {record[0]: record for record in functions}
        self.classes = {record[2]: record for record in classes}
        self.source = ast.parse(text or "", filename=f"<swift:{self.name}:source>")
        source_documentation = ast.get_docstring(self.source, clean=False)
        if source_documentation is not None:
            self.documentation = source_documentation

        self.declarations = {}
        self.aliases = {}
        self.variables = {}
        self.children = set()
        self.is_package = False
        names = set(self.functions) | set(self.classes)
        names.update(
            name.id
            for statement in self.source.body
            for name in ast.walk(statement)
            if isinstance(name, ast.Name) and isinstance(name.ctx, ast.Store)
        )
        names.update(
            statement.name
            for statement in self.source.body
            if isinstance(statement, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef))
        )
        self.annotations = Annotations(self.name, names)
        self._read_source()

    def render(self) -> str:
        body = self._body()
        imports = self._imports()
        lines = [_HEADER]
        docs = documentation(self.documentation)
        if docs:
            lines += ["", *docs]
        if imports:
            lines += ["", *sorted(imports)]
        if body:
            lines += ["", "", *body]

        text = "\n".join(lines) + "\n"
        # Validate every output before the caller replaces its destination directory.
        ast.parse(text, filename=self.name + ".pyi")
        return text

    def _read_source(self) -> None:
        for statement in self.source.body:
            if isinstance(statement, (ast.Import, ast.ImportFrom)):
                self.annotations.read_import(statement)
            elif isinstance(statement, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                self._discard(statement.name)
                self.declarations[statement.name] = statement
            elif isinstance(statement, ast.TypeAlias):
                self._discard(statement.name.id)
                self.aliases[statement.name.id] = ast.unparse(statement)
            elif isinstance(statement, (ast.Assign, ast.AnnAssign)):
                self._read_assignment(statement)
            elif isinstance(statement, ast.Delete):
                for target in statement.targets:
                    if isinstance(target, ast.Name):
                        self._discard(target.id)

    def _read_assignment(self, statement: ast.Assign | ast.AnnAssign) -> None:
        targets = statement.targets if isinstance(statement, ast.Assign) else [statement.target]
        for target in targets:
            if not isinstance(target, ast.Name):
                continue

            self.is_package |= target.id == "__path__"
            annotation = (
                ast.unparse(statement.annotation)
                if isinstance(statement, ast.AnnAssign)
                else self._infer(statement.value)
            )
            self._discard(target.id)
            self.variables[target.id] = annotation

    def _discard(self, name: str) -> None:
        for values in (
            self.functions,
            self.classes,
            self.declarations,
            self.variables,
            self.aliases,
        ):
            values.pop(name, None)

    def _infer(self, value: ast.expr) -> str:
        if isinstance(value, ast.Constant):
            return "None" if value.value is None else type(value.value).__name__
        if isinstance(value, ast.Name):
            return self.variables.get(value.id, "object")
        if isinstance(value, ast.Call):
            name = ast.unparse(value.func)
            if name in self.classes:
                return self.name + "." + name
            if name in BUILTINS:
                return name
        if isinstance(value, ast.Attribute):
            owner = self._infer(value.value)
            return self.fields.get(owner, {}).get(value.attr, "object")
        if isinstance(value, ast.List):
            items = {self._infer(item) for item in value.elts}
            return "list[" + (next(iter(items)) if len(items) == 1 else "object") + "]"
        if isinstance(value, ast.Dict):
            string_keys = all(
                isinstance(key, ast.Constant) and isinstance(key.value, str) for key in value.keys
            )
            return "dict[str, object]" if string_keys else "dict[object, object]"

        return "object"

    def _body(self) -> list[str]:
        body = []

        def append(lines):
            if body:
                body.extend(["", ""])
            body.extend(lines)

        def depth(record):
            base = record[1]
            return 0 if base is None else 1 + self._depth(base)

        for record in sorted(self.classes.values(), key=lambda record: (depth(record), record[2])):
            append(exports.render_class(record, self.annotations, self.bindings))
        for name, statement in sorted(self.declarations.items()):
            if not name.startswith("_") and isinstance(statement, ast.ClassDef):
                append(source.render_class(statement))
        for name, alias in sorted(self.aliases.items()):
            if not name.startswith("_"):
                append([alias])

        variables = self._variables()
        if variables:
            append(variables)

        source_functions = {
            name: statement
            for name, statement in self.declarations.items()
            if not name.startswith("_")
            and isinstance(statement, (ast.FunctionDef, ast.AsyncFunctionDef))
        }
        for name in sorted(self.functions.keys() | source_functions.keys()):
            if name in self.functions:
                append(exports.render_function(self.functions[name], self.annotations))
            else:
                append(source.render_function(source_functions[name]))

        return body

    def _variables(self) -> list[str]:
        lines = []
        for name, annotation in sorted(self.variables.items()):
            if not name.startswith("_"):
                bindings = [
                    binding
                    for binding in self.bindings.values()
                    if f"{binding[0]}.{binding[1]}" in annotation
                ]
                lines.append(name + ": " + self.annotations.resolve((annotation, bindings)))

        return lines

    def _imports(self) -> set[str]:
        imports = self.annotations.render_imports()
        imports.update(
            f"from . import {name} as {name}"
            for name in self.children
            if name not in self.variables and name not in self.declarations
        )
        return imports

    def _depth(self, key) -> int:
        module, name = self.bindings[key]
        if module != self.name or name not in self.classes:
            return 0

        base = self.classes[name][1]
        return 0 if base is None else 1 + self._depth(base)
