import _NIOFileSystem

extension StandardLibraryBuilder {
    func writeResources(_ library: Library) async throws {
        // Escape arbitrary bytes as C11 string contents, including trigraphs and octal digits.
        let literals = (0 ... 255).map { byte in
            switch byte {
            case 9:
                "\\t"
            case 10:
                "\\n"
            case 13:
                "\\r"
            case 34:
                "\\\""
            case 63:
                "\\?"
            case 92:
                "\\\\"
            case 32 ... 126:
                String(Unicode.Scalar(UInt8(byte)))
            default:
                "\\\(byte >> 6)\((byte >> 3) & 7)\(byte & 7)"
            }
        }

        func encodeChunk(_ bytes: some Collection<UInt8>, column: inout Int) -> String {
            var source = ""
            source.reserveCapacity(bytes.count * 4)
            for byte in bytes {
                if column == 64 {
                    source += "\"\n    \""
                    column = 0
                }
                source += literals[Int(byte)]
                column += 1
            }
            return source
        }

        try await writeGeneratedSource("Resources.c") { writer in
            func writeResource(_ resource: Resource, index: Int) async throws {
                let declaration = "static const unsigned char resource_\(index)[] =\n    \""
                try await writer.write(contentsOf: declaration.utf8)

                var column = 0
                try await workspace
                    .fileSystem
                    .withFileHandle(forReadingAt: resource.source) { handle in
                        for try await chunk in handle.readChunks(chunkLength: .kibibytes(64)) {
                            let source = encodeChunk(chunk.readableBytesView, column: &column)
                            try await writer.write(contentsOf: source.utf8)
                        }
                    }

                try await writer.write(contentsOf: "\";\n\n".utf8)
            }

            let header = """
            /* Generated by CPythonBuild. Source and resource bytes have process lifetime. */
            #include "embedded_data.h"

            """
            try await writer.write(contentsOf: header.utf8)
            for (index, resource) in library.resources.enumerated() {
                try await writeResource(resource, index: index)
            }

            try await Self.writeResourceCatalog(library.resources, to: &writer)
        }
    }

    private static func writeResourceCatalog(
        _ resources: [Resource],
        to writer: inout BufferedWriter<WriteFileHandle>,
    ) async throws {
        let declaration = "const CPythonEmbeddedResource CPythonEmbeddedResources[] = {\n"
        try await writer.write(contentsOf: declaration.utf8)

        for (index, resource) in resources.enumerated() {
            let entry = "    {\(resource.path.quotedSourceLiteral), resource_\(index), sizeof(resource_\(index)) - 1},\n"
            try await writer.write(contentsOf: entry.utf8)
        }

        try await writer.write(contentsOf: """
        };
        const size_t CPythonEmbeddedResourceCount =
            sizeof(CPythonEmbeddedResources) / sizeof(CPythonEmbeddedResources[0]);

        """.utf8)
    }
}
